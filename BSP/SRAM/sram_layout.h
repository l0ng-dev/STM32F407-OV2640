/** @file sram_layout.h
 * @brief FSMC 外部 SRAM 的图像缓冲和模型数据区域划分。
 * 地址和容量供启动自检、采集、推理及编译期边界检查使用。
 */
#ifndef BSP_SRAM_LAYOUT_H
#define BSP_SRAM_LAYOUT_H

/* FSMC 初始化及启动自检后方可使用；固定地址区不由启动代码清零。 */
#define SRAM_LAYOUT_BASE              0x68000000UL
#define SRAM_LAYOUT_SIZE              0x00100000UL
#define SRAM_LAYOUT_JPEG_BASE         SRAM_LAYOUT_BASE
#define SRAM_LAYOUT_JPEG_SIZE         65536UL
#define SRAM_LAYOUT_AI_BASE           0x68010000UL
#define SRAM_LAYOUT_AI_SIZE           76804UL
#define SRAM_LAYOUT_RGB_BASE          0x68022C20UL
#define SRAM_LAYOUT_RGB_SIZE          153600UL
#define SRAM_LAYOUT_INPUT_BASE        0x68048420UL
#define SRAM_LAYOUT_INPUT_SIZE        76800UL
#define SRAM_LAYOUT_JPEG2_BASE        0x6805B020UL
#define SRAM_LAYOUT_JPEG2_SIZE        65536UL
#define SRAM_LAYOUT_RGB2_BASE         0x68074020UL
#define SRAM_LAYOUT_RGB2_SIZE         153600UL

/* 固定地址按顺序检查不重叠且不超过器件；运行时所有权由应用调度。 */
#if (SRAM_LAYOUT_JPEG_BASE + SRAM_LAYOUT_JPEG_SIZE > SRAM_LAYOUT_AI_BASE) || \
    (SRAM_LAYOUT_AI_BASE + SRAM_LAYOUT_AI_SIZE > SRAM_LAYOUT_RGB_BASE) || \
    (SRAM_LAYOUT_RGB_BASE + SRAM_LAYOUT_RGB_SIZE > SRAM_LAYOUT_INPUT_BASE) || \
    (SRAM_LAYOUT_INPUT_BASE + SRAM_LAYOUT_INPUT_SIZE > SRAM_LAYOUT_JPEG2_BASE) || \
    (SRAM_LAYOUT_JPEG2_BASE + SRAM_LAYOUT_JPEG2_SIZE > SRAM_LAYOUT_RGB2_BASE) || \
    (SRAM_LAYOUT_RGB2_BASE + SRAM_LAYOUT_RGB2_SIZE > SRAM_LAYOUT_BASE + SRAM_LAYOUT_SIZE)
#error "External SRAM regions overlap or exceed the device"
#endif

#endif
